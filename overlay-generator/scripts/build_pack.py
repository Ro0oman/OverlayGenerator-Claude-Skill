#!/usr/bin/env python3
"""build_pack.py · OverlayGenerator

Turns a pack source folder into the folder + zip the streamer downloads.
Pure Python 3, no dependencies.

    python3 build_pack.py <pack-folder> [--out <dir>] [--no-render]

Source folder (written by Claude):
    pack.json            the recipe: scenes, state, actions, panel cards, alerts, texts
    overlays/*.html      one page per scene (+ shared css/js of the pack)
    fonts/  sounds/      bundled files (no internet at stream time)
    GUIDE.md             the step-by-step guide, in the pack language (any guide*/guía*/… name)

Output (<out>/<id>/ and <out>/<id>.zip):
    panel.html  preview.html  pack.json  GUIDE.md  overlays/  fonts/  engine/
The id and file names never change between versions, so a new version can be unzipped over the old one.
"""
import json, os, re, shutil, subprocess, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ENGINE = os.path.normpath(os.path.join(HERE, '..', 'assets', 'engine'))
sys.path.insert(0, HERE)
from validate_pack import validate  # noqa: E402

ENGINE_FILES = ['core.js', 'obs-link.js', 'twitch.js', 'ovg.js', 'panel.js', 'panel.css', 'panel-strings.js']
SKIP = {'.DS_Store', 'Thumbs.db', 'node_modules', '.git', 'checks'}


def read_engine_version():
    try:
        return json.load(open(os.path.join(ENGINE, 'VERSION.json')))['engine']
    except Exception:
        return '1.0.0'


def panel_closed_text(lang):
    src = open(os.path.join(ENGINE, 'panel-strings.js'), encoding='utf-8').read()
    block = src.split(lang[:2] + ': {', 1)
    if len(block) < 2:
        return None
    m = re.search(r"panelClosed:\s*'([^']*)'", block[1])
    return m.group(1) if m else None


def _inside(path, folder):
    """True if path is folder itself or anything under it (both already resolved)."""
    return os.path.commonpath([path, folder]) == folder


def overlapping(src, dest):
    """The build deletes dest before copying src into it: they must not be the same folder or nest."""
    a, b = os.path.realpath(src), os.path.realpath(dest)
    return _inside(a, b) or _inside(b, a)


def build(src, out, render=True):
    src = os.path.abspath(src)
    rep, pack = validate(src)
    rep.print()
    if rep.fails:
        print('\nBuild stopped: fix the FAIL lines first.')
        return None
    pid = pack['id']
    dest = os.path.join(out, pid)
    # Never delete the source: with the default --out ".", a source folder named like the pack id IS the output.
    for path in (dest, os.path.join(out, pid + '-checks')):
        if overlapping(src, path):
            print('\nBuild stopped: the output %s overlaps the pack source %s.\n'
                  'Nothing was deleted. Pass --out with a folder outside the source, e.g. --out ../build' % (os.path.abspath(path), src))
            return None
    if os.path.isdir(dest):
        shutil.rmtree(dest)
    shutil.copytree(src, dest, ignore=lambda d, names: [n for n in names if n in SKIP or n.endswith('.zip')])

    # engine
    eng = os.path.join(dest, 'engine')
    os.makedirs(eng, exist_ok=True)
    for f in ENGINE_FILES:
        shutil.copy2(os.path.join(ENGINE, f), os.path.join(eng, f))
    pack['engine'] = read_engine_version()
    ui = pack.setdefault('ui', {})
    if 'panelClosed' not in ui:
        t = panel_closed_text(pack.get('lang', 'en'))
        if t:
            ui['panelClosed'] = t
    with open(os.path.join(eng, 'pack.js'), 'w', encoding='utf-8') as fh:
        fh.write('/* generated by build_pack.py from pack.json · do not edit by hand */\n')
        fh.write('window.PACK = ' + json.dumps(pack, ensure_ascii=False, indent=1) + ';\n')
    with open(os.path.join(dest, 'pack.json'), 'w', encoding='utf-8') as fh:
        json.dump(pack, fh, ensure_ascii=False, indent=2)

    # panel + preview at the root
    for f in ('panel.html', 'preview.html'):
        html = open(os.path.join(ENGINE, f), encoding='utf-8').read()
        html = re.sub(r'<title>.*?</title>', '<title>%s · %s</title>' % (pack['name'], 'panel' if f == 'panel.html' else 'preview'), html, count=1)
        if f == 'panel.html':
            html = html.replace('<html>', '<html lang="%s">' % pack.get('lang', 'en'), 1)
        open(os.path.join(dest, f), 'w', encoding='utf-8').write(html)

    # optional render checks
    if render:
        checker = os.path.join(HERE, 'check_render.js')
        try:
            root = subprocess.run(['npm', 'root', '-g'], capture_output=True, text=True, timeout=30).stdout.strip()
            env = dict(os.environ, NODE_PATH=root)
            print('\n== render checks')
            r = subprocess.run(['node', checker, dest, '--out', os.path.join(out, pid + '-checks')], env=env, timeout=900)
            if r.returncode == 3:
                print('  (Playwright not available here: render checks skipped)')
        except (FileNotFoundError, subprocess.TimeoutExpired):
            print('  (Node not available here: render checks skipped)')

    # zip
    zpath = os.path.join(out, pid + '.zip')
    with zipfile.ZipFile(zpath, 'w', zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(dest):
            for f in files:
                p = os.path.join(root, f)
                z.write(p, os.path.relpath(p, out))
    print('\nPack ready: %s\n            %s' % (dest, zpath))
    return dest


if __name__ == '__main__':
    args = sys.argv[1:]
    if not args:
        print(__doc__); sys.exit(2)
    out = '.'
    if '--out' in args:
        i = args.index('--out'); out = args[i + 1]; del args[i:i + 2]
    render = '--no-render' not in args
    args = [a for a in args if a != '--no-render']
    os.makedirs(out, exist_ok=True)
    sys.exit(0 if build(args[0], out, render) else 1)
